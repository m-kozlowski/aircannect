"""Validate WebUI catalogs and synchronize their firmware language choices."""

import argparse
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[2]
PLURALS = {"zero", "one", "two", "few", "many", "other"}


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate catalog key: {key}")
        result[key] = value
    return result


def load_catalogs(root=ROOT):
    catalogs = {}
    for path in sorted((Path(root) / "www/i18n").glob("*.json")):
        if len(path.stem) > 15 or not re.fullmatch(
                r"[a-z]{2}(?:-[A-Za-z0-9]{2,8})*", path.stem):
            raise ValueError(f"invalid language tag: {path.stem}")
        catalog = json.loads(path.read_text(encoding="utf-8"),
                             object_pairs_hook=unique_object)
        if not isinstance(catalog, dict):
            raise ValueError(f"{path.stem}: expected a catalog object")
        for key, value in catalog.items():
            variants = value.values() if isinstance(value, dict) else [value]
            if not variants or any(not isinstance(text, str) or not text
                                   for text in variants):
                raise ValueError(f"{path.stem}: invalid text for {key}")
            if isinstance(value, dict) and (
                    "other" not in value or not set(value) <= PLURALS):
                raise ValueError(f"{path.stem}: invalid plurals for {key}")
        if not isinstance(catalog.get("language.name"), str):
            raise ValueError(f"{path.stem}: language.name is required")
        catalogs[path.stem] = catalog

    if "en" not in catalogs:
        raise ValueError("complete English catalog is required")
    base = catalogs["en"]
    for tag, catalog in catalogs.items():
        extra = sorted(catalog.keys() - base.keys())
        if extra:
            raise ValueError(f"{tag}: unknown keys={extra}")
        for key, value in catalog.items():
            reference = base[key]
            if isinstance(value, dict) != isinstance(reference, dict):
                raise ValueError(f"{tag}: plural shape differs for {key}")
            texts = list(value.values()) if isinstance(value, dict) else [value]
            references = (list(reference.values())
                          if isinstance(reference, dict) else [reference])
            params = set(re.findall(r"\{(\w+)\}", references[0]))
            for text in texts + references:
                if set(re.findall(r"\{(\w+)\}", text)) != params:
                    raise ValueError(f"{tag}: parameters differ for {key}")
    return catalogs


def language_header(catalogs):
    rows = [('auto', catalogs['en']['config.option.ui_language.auto'])]
    rows.extend((tag, catalog['language.name'])
                for tag, catalog in catalogs.items())
    return (
        '// Generated by python/tools/web_localization.py --sync.\n'
        '// Do not edit; language choices come from www/i18n/*.json.\n'
        'static constexpr AppConfigEnumValue UI_LANGUAGE_VALUES[] = {\n' +
        ''.join('    {' + json.dumps(tag) + ', ' +
                json.dumps(name, ensure_ascii=False) + '},\n'
                for tag, name in rows) + '};\n')


def check_language_header(root, catalogs, sync=False):
    path = Path(root) / 'include/ui_languages_generated.inc'
    expected = language_header(catalogs)
    if sync:
        path.write_text(expected, encoding='utf-8')
    elif not path.exists() or path.read_text(encoding='utf-8') != expected:
        raise ValueError('language choices are stale; run '
                         'python3 python/tools/web_localization.py --sync')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--sync', action='store_true')
    args = parser.parse_args()
    catalogs = load_catalogs()
    check_language_header(ROOT, catalogs, args.sync)
    print(f"WebUI catalogs: {len(catalogs)} languages, "
          f"{len(catalogs['en'])} English keys")


if __name__ == '__main__':
    main()
